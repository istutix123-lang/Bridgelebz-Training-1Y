public class Student {


    private int age;
    private String name;
    private int id;
    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
    public Student(int age,String name,int id){
        this.age=age;
        this.name=name;
        this.id=id;
    }
}
